fn marching_cubes<F: Fn(f64, f64, f64) -> f64>(
    fn_: &F, box_: &OBB, nx: usize, ny: usize, nz: usize, isovalue: f64,
) -> Mesh {
    let mn = box_.min_point();
    let mx = box_.max_point();
    let min_x = mn[0];
    let min_y = mn[1];
    let min_z = mn[2];
    let dx = (mx[0] - min_x) / nx as f64;
    let dy = (mx[1] - min_y) / ny as f64;
    let dz = (mx[2] - min_z) / nz as f64;
    let h = dx.min(dy).min(dz) * 0.5;
    let nxg = nx + 1;
    let nyg = ny + 1;
    let nzg = nz + 1;
    let mut field = vec![0.0f64; nxg * nyg * nzg];
    for i in 0..nxg {
        for j in 0..nyg {
            for k in 0..nzg {
                field[i * nyg * nzg + j * nzg + k] =
                    fn_(min_x + i as f64 * dx, min_y + j as f64 * dy, min_z + k as f64 * dz);
            }
        }
    }
    let mut edge_x = vec![-1i64; nx * nyg * nzg];
    let mut edge_y = vec![-1i64; nxg * ny * nzg];
    let mut edge_z = vec![-1i64; nxg * nyg * nz];
    let mut mesh = Mesh::new();

    for i in 0..nx {
        for j in 0..ny {
            for k in 0..nz {
                let pt = [
                    [min_x + i as f64 * dx,       min_y + j as f64 * dy,       min_z + k as f64 * dz],
                    [min_x + (i+1) as f64 * dx,   min_y + j as f64 * dy,       min_z + k as f64 * dz],
                    [min_x + (i+1) as f64 * dx,   min_y + (j+1) as f64 * dy,   min_z + k as f64 * dz],
                    [min_x + i as f64 * dx,        min_y + (j+1) as f64 * dy,   min_z + k as f64 * dz],
                    [min_x + i as f64 * dx,        min_y + j as f64 * dy,       min_z + (k+1) as f64 * dz],
                    [min_x + (i+1) as f64 * dx,   min_y + j as f64 * dy,       min_z + (k+1) as f64 * dz],
                    [min_x + (i+1) as f64 * dx,   min_y + (j+1) as f64 * dy,   min_z + (k+1) as f64 * dz],
                    [min_x + i as f64 * dx,        min_y + (j+1) as f64 * dy,   min_z + (k+1) as f64 * dz],
                ];
                let val = [
                    field[i * nyg * nzg + j * nzg + k],
                    field[(i+1) * nyg * nzg + j * nzg + k],
                    field[(i+1) * nyg * nzg + (j+1) * nzg + k],
                    field[i * nyg * nzg + (j+1) * nzg + k],
                    field[i * nyg * nzg + j * nzg + (k+1)],
                    field[(i+1) * nyg * nzg + j * nzg + (k+1)],
                    field[(i+1) * nyg * nzg + (j+1) * nzg + (k+1)],
                    field[i * nyg * nzg + (j+1) * nzg + (k+1)],
                ];
                let mut cube_idx: usize = 0;
                for v in 0..8 {
                    if val[v] < isovalue {
                        cube_idx |= 1 << v;
                    }
                }
                if cube_idx == 0 || cube_idx == 255 {
                    continue;
                }
                let tris = &TRI_TABLE[cube_idx];
                let mut t = 0;
                while t < 15 {
                    if tris[t] == -1 {
                        break;
                    }
                    let mut tri_verts = [0usize; 3];
                    for s in 0..3 {
                        let e = tris[t + s] as usize;
                        let (arr_id, idx) = match e {
                            0  => (0usize, i * nyg * nzg + j * nzg + k),
                            1  => (1, (i+1) * ny * nzg + j * nzg + k),
                            2  => (0, i * nyg * nzg + (j+1) * nzg + k),
                            3  => (1, i * ny * nzg + j * nzg + k),
                            4  => (0, i * nyg * nzg + j * nzg + (k+1)),
                            5  => (1, (i+1) * ny * nzg + j * nzg + (k+1)),
                            6  => (0, i * nyg * nzg + (j+1) * nzg + (k+1)),
                            7  => (1, i * ny * nzg + j * nzg + (k+1)),
                            8  => (2, i * nyg * nz + j * nz + k),
                            9  => (2, (i+1) * nyg * nz + j * nz + k),
                            10 => (2, (i+1) * nyg * nz + (j+1) * nz + k),
                            _  => (2, i * nyg * nz + (j+1) * nz + k),
                        };
                        let slot_val = match arr_id {
                            0 => edge_x[idx],
                            1 => edge_y[idx],
                            _ => edge_z[idx],
                        };
                        let vk = if slot_val >= 0 {
                            slot_val as usize
                        } else {
                            let ca = EDGE_VERTICES[e][0];
                            let cb = EDGE_VERTICES[e][1];
                            let va = val[ca];
                            let vb = val[cb];
                            let interp = if (vb - va).abs() < 1e-12 { 0.5 } else { (isovalue - va) / (vb - va) };
                            let px = pt[ca][0] + interp * (pt[cb][0] - pt[ca][0]);
                            let py = pt[ca][1] + interp * (pt[cb][1] - pt[ca][1]);
                            let pz = pt[ca][2] + interp * (pt[cb][2] - pt[ca][2]);
                            let gnx = fn_(px + h, py, pz) - fn_(px - h, py, pz);
                            let gny = fn_(px, py + h, pz) - fn_(px, py - h, pz);
                            let gnz = fn_(px, py, pz + h) - fn_(px, py, pz - h);
                            let gl = (gnx*gnx + gny*gny + gnz*gnz).sqrt();
                            let new_vk = mesh.add_vertex(Point::new(px, py, pz), None);
                            if let Some(v) = mesh.vertex.get_mut(&new_vk) {
                                if gl > 1e-12 {
                                    v.set_normal(gnx / gl, gny / gl, gnz / gl);
                                } else {
                                    v.set_normal(gnx, gny, gnz);
                                }
                            }
                            match arr_id {
                                0 => edge_x[idx] = new_vk as i64,
                                1 => edge_y[idx] = new_vk as i64,
                                _ => edge_z[idx] = new_vk as i64,
                            }
                            new_vk
                        };
                        tri_verts[s] = vk;
                    }
                    mesh.add_face(vec![tri_verts[0], tri_verts[2], tri_verts[1]], None);
                    t += 3;
                }
            }
        }
    }
    mesh.strip_render_data();
    mesh
}

fn merge_meshes(m1: Mesh, m2: Mesh) -> Mesh {
    let (v1, f1) = m1.to_vertices_and_faces();
    let (v2, f2) = m2.to_vertices_and_faces();
    let offset = v1.len();
    let mut verts = v1;
    verts.extend(v2);
    let mut faces: Vec<Vec<usize>> = f1;
    for f in f2 {
        faces.push(f.into_iter().map(|idx| idx + offset).collect());
    }
    let mut result = Mesh::from_vertices_and_faces(verts, faces);
    result.strip_render_data();
    result
}

impl MeshIso {
    pub fn eval(tpms_type: TpmsType, x: f64, y: f64, z: f64, period: f64) -> f64 {
        let bx = x / period;
        let by = y / period;
        let bz = z / period;
        match tpms_type {
            TpmsType::GYROID =>
                bx.sin()*by.cos() + by.sin()*bz.cos() + bz.sin()*bx.cos(),
            TpmsType::SCHWARZ_P =>
                bx.cos() + by.cos() + bz.cos(),
            TpmsType::DIAMOND =>
                bx.sin()*by.sin()*bz.sin()
                + bx.sin()*by.cos()*bz.cos()
                + bx.cos()*by.sin()*bz.cos()
                + bx.cos()*by.cos()*bz.sin(),
            TpmsType::NEOVIUS =>
                3.0*(bx.cos()+by.cos()+bz.cos()) + 4.0*bx.cos()*by.cos()*bz.cos(),
            TpmsType::IWP =>
                2.0*(bx.cos()*by.cos()+by.cos()*bz.cos()+bz.cos()*bx.cos())
                - ((2.0*bx).cos()+(2.0*by).cos()+(2.0*bz).cos()),
            TpmsType::LIDINOID =>
                (2.0*bx).sin()*by.cos()*bz.sin()
                + (2.0*by).sin()*bz.cos()*bx.sin()
                + (2.0*bz).sin()*bx.cos()*by.sin()
                + (2.0*bx).cos()*(2.0*by).cos()
                + (2.0*by).cos()*(2.0*bz).cos()
                + (2.0*bz).cos()*(2.0*bx).cos(),
            TpmsType::FISCHER_KOCH_S =>
                (2.0*bx).cos()*by.sin()*bz.cos()
                + (2.0*by).cos()*bz.sin()*bx.cos()
                + (2.0*bz).cos()*bx.sin()*by.cos(),
            TpmsType::FRD =>
                4.0*bx.cos()*by.cos()*bz.cos()
                - ((2.0*bx).cos()*(2.0*by).cos()
                 + (2.0*by).cos()*(2.0*bz).cos()
                 + (2.0*bz).cos()*(2.0*bx).cos()),
            TpmsType::PMY =>
                2.0*bx.cos()*by.cos()*bz.cos()
                + (2.0*bx).sin()*by.sin()
                + bx.sin()*(2.0*bz).sin()
                + (2.0*by).sin()*bz.sin(),
        }
    }

    pub fn from_tpms(tpms_type: TpmsType, box_: &OBB,
                     nx: usize, ny: usize, nz: usize,
                     isovalue: f64, period: f64,
                     mode: TpmsMode, thickness: f64) -> Mesh {
        let fn_tpms = move |x: f64, y: f64, z: f64| -> f64 {
            MeshIso::eval(tpms_type, x, y, z, period / (2.0 * std::f64::consts::PI))
        };
        if mode == TpmsMode::SOLID {
            return marching_cubes(&fn_tpms, box_, nx, ny, nz, isovalue);
        }
        let m1 = marching_cubes(&fn_tpms, box_, nx, ny, nz, isovalue - thickness);
        let m2 = marching_cubes(&fn_tpms, box_, nx, ny, nz, isovalue + thickness);
        merge_meshes(m1, m2)
    }

    pub fn from_function<F: Fn(f64, f64, f64) -> f64>(
        fn_: F, box_: &OBB, nx: usize, ny: usize, nz: usize, isovalue: f64,
    ) -> Mesh {
        marching_cubes(&fn_, box_, nx, ny, nz, isovalue)
    }

    pub fn sdf_sphere(cx: f64, cy: f64, cz: f64, r: f64, x: f64, y: f64, z: f64) -> f64 {
        let dx = x - cx;
        let dy = y - cy;
        let dz = z - cz;
        (dx*dx + dy*dy + dz*dz).sqrt() - r
    }

    pub fn sdf_box(cx: f64, cy: f64, cz: f64, hx: f64, hy: f64, hz: f64,
                   x: f64, y: f64, z: f64) -> f64 {
        let qx = (x - cx).abs() - hx;
        let qy = (y - cy).abs() - hy;
        let qz = (z - cz).abs() - hz;
        let mx = qx.max(0.0);
        let my = qy.max(0.0);
        let mz = qz.max(0.0);
        (mx*mx + my*my + mz*mz).sqrt() + qx.max(qy).max(qz).min(0.0)
    }

    pub fn sdf_capsule(p0: &Point, p1: &Point, r: f64, x: f64, y: f64, z: f64) -> f64 {
        let pax = x - p0[0];
        let pay = y - p0[1];
        let paz = z - p0[2];
        let bax = p1[0] - p0[0];
        let bay = p1[1] - p0[1];
        let baz = p1[2] - p0[2];
        let h = ((pax*bax + pay*bay + paz*baz) / (bax*bax + bay*bay + baz*baz)).max(0.0).min(1.0);
        let dx = pax - h * bax;
        let dy = pay - h * bay;
        let dz = paz - h * baz;
        (dx*dx + dy*dy + dz*dz).sqrt() - r
    }

    pub fn sdf_torus(cx: f64, cy: f64, cz: f64, major_r: f64, minor_r: f64,
                     x: f64, y: f64, z: f64) -> f64 {
        let lx = x - cx;
        let ly = y - cy;
        let lz = z - cz;
        let q = (lx*lx + ly*ly).sqrt() - major_r;
        (q*q + lz*lz).sqrt() - minor_r
    }

    pub fn sdf_plane(nx: f64, ny: f64, nz: f64, d: f64, x: f64, y: f64, z: f64) -> f64 {
        nx*x + ny*y + nz*z - d
    }

    pub fn smooth_union(a: f64, b: f64, k: f64) -> f64 {
        -((-k * a).exp() + (-k * b).exp()).ln() / k
    }

    pub fn smooth_subtract(a: f64, b: f64, k: f64) -> f64 {
        -MeshIso::smooth_union(-a, b, k)
    }

    pub fn smooth_intersect(a: f64, b: f64, k: f64) -> f64 {
        -MeshIso::smooth_union(-a, -b, k)
    }
}
