#[allow(non_camel_case_types)]
#[derive(Clone, Copy, PartialEq)]
pub enum TpmsType {
    GYROID = 0,
    SCHWARZ_P = 1,
    DIAMOND = 2,
    NEOVIUS = 3,
    IWP = 4,
    LIDINOID = 5,
    FISCHER_KOCH_S = 6,
    FRD = 7,
    PMY = 8,
}

#[derive(Clone, Copy, PartialEq)]
pub enum TpmsMode {
    SOLID = 0,
    SHEET = 1,
    SHELL = 2,
}

